#!/usr/bin/env node
/**
 * Generate the reference pages from src/data/*.json (dumped from the engine by
 * tools/capture/dump-data.mjs):
 *   docs/reference/conditions.mdx, actions.mdx, expressions.mdx, scripting-api.mdx
 *
 *   npm run docs:reference
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const data = (n) => JSON.parse(readFileSync(join(root, 'src/data', n + '.json'), 'utf8'));
const outDir = join(root, 'docs/reference');
mkdirSync(outDir, { recursive: true });

/** Escape text for MDX (outside code). */
const t = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/\{/g, '&#123;').replace(/\}/g, '&#125;').replace(/\|/g, '\\|');
/** Inline code (backticks inside are replaced). */
const c = (s) => '`' + String(s ?? '').replace(/`/g, "'").replace(/\|/g, '\\|') + '`';
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const HEADER = '{/* Generated by tools/gen-reference.mjs from the engine source — do not edit by hand. */}\n';

const PARAM_TYPES = {
  expression: 'Expression', number: 'Number (expression)', boolean: 'Yes / No (expression)', string: 'Text', object: 'Object or #tag',
  variable: 'Variable', choice: 'Choice', button: 'Touch button', key: 'Keyboard key', sound: 'Sound', image: 'Image', scene: 'Scene',
  color: 'Color', behavior: 'Behavior', prefab: 'Object / prefab', group: 'Event group', tag: 'Tag', function: 'Function',
};

const TARGET_LABEL = { system: 'System', input: 'Input', audio: 'Audio', camera: 'Camera', object: 'an object' };

/** "{object} collides with {other}" → "Player collides with other" style sample. */
function displayOf(a) {
  return a.display.replace(/\{object\}/g, '‹Object›').replace(/\{(\w+)\}/g, (_, id) => {
    const p = a.params.find((x) => x.id === id);
    return '‹' + (p ? p.label : id) + '›';
  });
}

function acePage(kind) {
  const { categories, icons, list } = data('aces');
  const items = list.filter((a) => a.kind === kind);
  const word = kind === 'condition' ? 'Condition' : 'Action';
  const out = [];
  out.push('---', `title: ${word}s`, `description: Every ${kind} available in event sheets, with its parameters.`, `sidebar_label: ${word}s`, '---', '', HEADER);
  out.push(`# ${word}s`, '', kind === 'condition' ? '<Art name="block-when" size={180} />' : '<Art name="block-add" size={200} />', '');
  if (kind === 'condition') {
    out.push('Conditions are the **WHEN / IF** part of an event. All conditions of an event must be true for its actions to run (or *any* of them, in an OR block). A condition about an object **picks** the instances that match, so the actions only affect those. See [How events work](../logic/event-sheets).', '');
    out.push(':::info[Legend]', '- <span class="tge-pill trigger">⚡ Trigger</span> runs at the moment something happens (not every frame). It can’t be inverted.', '- <span class="tge-pill loop">🔁 Loop</span> repeats the rest of the event.', '- Most other conditions can be **inverted** (NOT) from the condition’s menu.', ':::', '');
  } else {
    out.push('Actions are the **DO** part of an event. They run from top to bottom when the event’s conditions are true. Actions on an object apply to the instances the conditions **picked** (or to all instances of that object if none were picked). See [How events work](../logic/event-sheets).', '');
    out.push(':::tip[Every value is an expression]', 'Number and text fields accept expressions, e.g. `Score + 1`, `"Score: " + Score`, `Player.x`, `random(1, 6)`. See [Expressions](./expressions).', ':::', '');
  }
  out.push(`There are **${items.length} ${kind}s**, grouped by category as in the ${word.toLowerCase()} picker.`, '');
  const cats = categories.filter((cat) => items.some((a) => a.category === cat));
  out.push(cats.map((cat) => `[${icons[cat]} ${cat}](#${slug(cat)})`).join(' · '), '');
  for (const cat of cats) {
    out.push(`## ${icons[cat]} ${cat} {/* #${slug(cat)} */}`, '');
    for (const a of items.filter((x) => x.category === cat)) {
      const pills = [];
      if (a.isTrigger) pills.push('<span class="tge-pill trigger">⚡ Trigger</span>');
      if (a.loop) pills.push('<span class="tge-pill loop">🔁 Loop</span>');
      if (a.isWait) pills.push('<span class="tge-pill">⏸ Waits</span>');
      out.push(`### ${t(a.label)} {/* #${slug(a.id)} */}`, '');
      out.push(`<span class="tge-ace-display">${t(displayOf(a))}</span>${pills.length ? ' ' + pills.join(' ') : ''}`, '');
      out.push(t(a.description), '');
      const where = a.objectRequired ? 'Pick an **object** (or a #tag) first, then this ' + kind + '.'
        : a.objectOptional ? `Found under **${TARGET_LABEL[a.target]}**; it can also be used on an object.`
        : `Found under **${TARGET_LABEL[a.target]}** in the picker.`;
      out.push(`- **Where:** ${where}`);
      out.push(`- **ID:** ${c(a.id)} (as saved in project files)`);
      if (a.params.length) {
        out.push('', '| Parameter | Type | Default | Notes |', '| --- | --- | --- | --- |');
        for (const p of a.params) {
          let notes = p.hint ? t(p.hint) : '';
          if (p.options) notes = (notes ? notes + ' ' : '') + 'Options: ' + p.options.map((o) => t(o.label)).join(', ');
          if (p.varScope === 'instance') notes = (notes ? notes + ' ' : '') + 'An instance variable of the object.';
          if (p.optional) notes = (notes ? notes + ' ' : '') + '*Optional.*';
          out.push(`| ${t(p.label)} | ${PARAM_TYPES[p.type] ?? p.type} | ${p.default != null && p.default !== '' ? c(p.default) : ''} | ${notes} |`);
        }
      } else out.push('- **Parameters:** none');
      out.push('');
    }
  }
  return out.join('\n');
}

function expressionsPage() {
  const e = data('expressions');
  const out = ['---', 'title: Expressions', 'description: Every function, property and value you can use inside event sheet expressions.', '---', '', HEADER, '# Expressions', '', '<Art name="block-collide" size={200} />', ''];
  out.push('Every number or text field in an event is an **expression**: a small formula the game works out while it runs. Type `10`, `Score + 1`, `"Score: " + Score`, `Player.x` or `random(1, 6)`.', '');
  out.push('## Values and operators', '');
  out.push('| Write | Meaning |', '| --- | --- |');
  const ops = [
    ['`12`, `3.5`, `-1`', 'Numbers'], ['`"text"` or `\'text\'`', 'Text (with quotes)'], ['`true`, `false`', 'Yes / no'],
    ['`+ - * / %` , `^`, `mod`', 'Math. `+` joins text when either side is text: `"Lives: " + Lives`'],
    ['`= <> != ≠ < <= ≤ > >= ≥`', 'Compare (gives true/false)'], ['`and or not` (also `& \\| !`)', 'Logic'],
    ['`cond ? a : b`', 'Pick a or b'], ['`Score`', 'A global, scene or local variable, by name'],
    ['`Player.x`', 'A property of an object (see below)'], ['`Enemy.hp`', 'An instance variable (also `Enemy.var("hp")`)'],
  ];
  for (const [a, b] of ops) out.push(`| ${a} | ${b} |`);
  out.push('', ':::note[Mistakes don’t crash the game]', 'If you mistype a name, the game keeps running: it shows a friendly message once and the unknown value counts as `0`. The event with the problem gets a red badge in the editor.', ':::', '');
  out.push('## Functions', '');
  const cats = [...new Set(e.functions.map((f) => f.category))];
  for (const cat of cats) {
    out.push(`### ${cat}`, '', '| Function | What it does |', '| --- | --- |');
    for (const f of e.functions.filter((x) => x.category === cat)) out.push(`| ${c(f.signature)} | ${t(f.description)} |`);
    out.push('');
  }
  out.push('## Object properties', '', 'Write the object’s name (or `Self` inside an action on that object), a dot, then the property: `Player.x`, `Coin.count`, `Self.angle`.', '');
  out.push('| Property | What it gives |', '| --- | --- |');
  for (const p of e.objectProps) out.push(`| ${c('.' + p.name.replace(/^\./, ''))} | ${t(p.description)} |`);
  out.push('', 'Inside an action on an object type, `Coin.x` means *the coin being processed*. With several picked coins, the action runs once per coin and each sees its own values.', '');
  out.push('## Built-in values', '', e.builtins.map((b) => c(b)).join(' · '), '');
  out.push('## Compare operators', '', 'Conditions such as *Compare variable* use: ' + e.compareOps.map((o) => c(o)).join(' '), '');
  return out.join('\n');
}

function apiPage() {
  const api = data('api');
  const snippets = data('snippets');
  const out = ['---', 'title: Scripting API', 'description: Every object, property and method available in JavaScript code scripts.', '---', '', HEADER, '# Scripting API', '', '<Art name="tile-code" size={95} />', ''];
  out.push('This is the complete list of what code scripts can use. It is the same list the code editor’s autocomplete and **API** help sheet show. For an introduction, read [Code scripts](../logic/scripting).', '');
  out.push('## Lifecycle functions', '', 'Define any of these in a script; the engine calls them.', '', '| Function | When it runs | Object script | Game script |', '| --- | --- | :-: | :-: |');
  for (const l of api.lifecycle) out.push(`| ${c(l.name + '(' + l.args + ')')} | ${t(l.doc)} | ✔ | ${l.global ? '✔' : ''} |`);
  out.push('');
  for (const g of api.groups) {
    out.push(`## \`${g.name}\` — ${t(g.title)} {/* #${slug(g.name)} */}`, '', t(g.doc), '');
    out.push('| Member | Type | Description |', '| --- | --- | --- |');
    for (const m of g.members) out.push(`| ${c(m.kind === 'method' ? m.name + (m.sig ?? '()') : m.name)} | ${m.type ? c(m.type) : ''} | ${t(m.doc)} |`);
    out.push('');
  }
  if (api.globals?.length) {
    out.push('## Globals', '', '| Name | Type | Description |', '| --- | --- | --- |');
    for (const m of api.globals) out.push(`| ${c(m.kind === 'method' ? m.name + (m.sig ?? '()') : m.name)} | ${m.type ? c(m.type) : ''} | ${t(m.doc)} |`);
    out.push('');
  }
  out.push('## Vectors', '', 'Positions, rotations and scales are `{x, y, z}` objects:', '', '| Member | Type | Description |', '| --- | --- | --- |');
  for (const m of api.vec3) out.push(`| ${c(m.name)} | ${c(m.type)} | ${t(m.doc)} |`);
  out.push('', '## Snippets', '', 'The code editor’s **Snippets** button inserts these ready-made pieces of code.', '');
  for (const s of snippets) {
    out.push(`### ${t(s.label ?? s.name ?? s.title)}`, '');
    if (s.description) out.push(t(s.description), '');
    out.push('```js', (s.code ?? s.body ?? '').trimEnd(), '```', '');
  }
  return out.join('\n');
}

writeFileSync(join(outDir, 'conditions.mdx'), acePage('condition'));
writeFileSync(join(outDir, 'actions.mdx'), acePage('action'));
writeFileSync(join(outDir, 'expressions.mdx'), expressionsPage());
writeFileSync(join(outDir, 'scripting-api.mdx'), apiPage());
console.log('reference pages written to docs/reference/');
